#!/usr/bin/env node
/**
 * Generates app/src/theme/tokens.ts from docs/design/design-tokens.json.
 * The JSON is the single source of truth: edit it, then run `npm run tokens`.
 * `npm run tokens:check` fails if the committed file is out of date.
 */
const fs = require('fs');
const path = require('path');
const prettier = require('prettier');

const root = path.resolve(__dirname, '..');
const source = path.resolve(root, '../docs/design/design-tokens.json');
const target = path.join(root, 'src/theme/tokens.ts');

// Face name per family and weight. The name equals both the file name and the
// PostScript name, so the same string works on iOS, Android and web.
const FACES = {
  heading: {700: 'BarlowCondensed-Bold', 800: 'BarlowCondensed-ExtraBold'},
  body: {400: 'DMSans-Regular', 500: 'DMSans-Medium', 700: 'DMSans-Bold'},
};

const round = n => Math.round(n * 100) / 100;

function build(tokens) {
  const typography = {};
  for (const [name, t] of Object.entries(tokens.type)) {
    const fontFamily = FACES[t.font] && FACES[t.font][t.weight];
    if (!fontFamily) {
      throw new Error(`No font face for "${name}" (${t.font} ${t.weight})`);
    }
    typography[name] = {
      fontFamily,
      fontSize: t.size,
      lineHeight: round(t.size * t.lineHeight),
      ...(t.tracking ? {letterSpacing: round(t.tracking * t.size)} : {}),
      ...(t.transform ? {textTransform: t.transform} : {}),
    };
  }

  return {
    colors: tokens.color,
    fontFaces: FACES,
    typography,
    space: tokens.space,
    radius: tokens.radius,
    border: tokens.border,
    size: tokens.size,
    layout: tokens.layout,
    motion: tokens.motion,
    pattern: tokens.pattern,
  };
}

async function render() {
  const tokens = JSON.parse(fs.readFileSync(source, 'utf8'));
  const body = JSON.stringify(build(tokens), null, 2);
  const code = [
    '// GENERATED by scripts/gen-tokens.js from docs/design/design-tokens.json.',
    '// Do not edit by hand: change the JSON and run `npm run tokens`.',
    `export const tokens = ${body} as const;`,
    '',
    'export type Tokens = typeof tokens;',
    '',
  ].join('\n');
  const config = await prettier.resolveConfig(target);
  return prettier.format(code, {...config, filepath: target});
}

async function main() {
  const output = await render();
  if (process.argv.includes('--check')) {
    const current = fs.existsSync(target)
      ? fs.readFileSync(target, 'utf8')
      : '';
    if (current !== output) {
      console.error(
        'src/theme/tokens.ts is out of date. Run `npm run tokens`.',
      );
      process.exit(1);
    }
    console.log('tokens.ts is up to date.');
    return;
  }
  fs.mkdirSync(path.dirname(target), {recursive: true});
  fs.writeFileSync(target, output);
  console.log(`Wrote ${path.relative(root, target)}`);
}

main().catch(err => {
  console.error(err);
  process.exit(1);
});
